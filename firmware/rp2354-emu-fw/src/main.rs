// ---------------------------------------------------------------------------
// RP2350 flash image header: vector table + picobin IMAGE_DEF
// ---------------------------------------------------------------------------
//
// The real bootrom validates the 20-byte IMAGE_DEF block in the first 4 KB of
// flash before jumping to the reset vector. This matches the reference layout
// generated by picoem `roms/rp2350/gen_blinky.py`:
//   IMAGE_TYPE = EXE | Secure | ARM | RP2350 = 0x1021
core::arch::global_asm!(
    r#"
    .syntax unified
    .thumb

    .section .vectors, "a", %progbits
    .word 0x20080000          /* initial SP (top of SRAM minus 8 KB) */
    .word _start + 1          /* reset */
    .word _default_fault + 1  /* NMI */
    .word _default_fault + 1  /* HardFault */
    .word _default_fault + 1  /* MemManage */
    .word _default_fault + 1  /* BusFault */
    .word _default_fault + 1  /* UsageFault */
    .word _default_fault + 1  /* SecureFault */
    .word 0                   /* reserved */
    .word 0                   /* reserved */
    .word 0                   /* reserved */
    .word _default_fault + 1  /* SVCall */
    .word _default_fault + 1  /* DebugMon */
    .word 0                   /* reserved */
    .word _default_fault + 1  /* PendSV */
    .word _default_fault + 1  /* SysTick */

    .section .picobin, "a", %progbits
    .word 0xFFFFDED3          /* PICOBIN_BLOCK_MARKER_START */
    .word 0x10210142          /* IMAGE_TYPE item: 0x42, size 1, type 0x1021 */
    .word 0x000001FF          /* LAST item */
    .word 0x00000000          /* next block offset (none) */
    .word 0xAB123579          /* PICOBIN_BLOCK_MARKER_END */

    .section .text._default_fault, "ax", %progbits
    .thumb_func
    .global _default_fault
_default_fault:
    b _default_fault
"#,
);

/// Mailbox compatible with `firmware/emu-tests` (see module docs).
#[repr(C)]
struct Mailbox {
    scenario: AtomicU32,
    status: AtomicU32,
    check: AtomicU32,
    detail: AtomicU32,
    hash: AtomicU32,
    magic: AtomicU32,
    /// Extra diagnostics (first mock violation index / panic message length).
    debug0: AtomicU32,
    /// Extra diagnostics (write count / panic line).
    debug1: AtomicU32,
    /// Extra diagnostics (panic file hash).
    debug2: AtomicU32,
    /// Extra diagnostics (panic column).
    debug3: AtomicU32,
}

/// Fixed SRAM mailbox address, shared with the host harness. 64 KB below the
/// initial stack pointer so firmware stack growth cannot clobber it.
const MAILBOX_ADDR: u32 = 0x2007_0000;

/// Access the shared mailbox.
///
/// SAFETY: `MAILBOX_ADDR` points at reserved SRAM that is never used by the
/// stack, heap or `.bss`; the memory is mapped for the whole program lifetime
/// and only atomic accesses are performed.
fn mailbox() -> &'static Mailbox {
    unsafe { &*(MAILBOX_ADDR as usize as *const Mailbox) }
}

/// Written last so the host never observes a half-updated result.
const MAILBOX_MAGIC: u32 = 0x4155_5242; // "AURB"
const STATUS_PASSED: u32 = 1;
const STATUS_FAILED: u32 = 2;
const STATUS_PANIC: u32 = 3;

/// SRAM address assumptions shared with `link.x` / the host harness.
const SCENARIO_ALLOC: u32 = 0;
const SCENARIO_READ_UIMLK: u32 = 1;
const SCENARIO_CONFIRM_SCREEN: u32 = 2;
const SCENARIO_NO_DEVICE: u32 = 3;

#[no_mangle]
pub extern "C" fn _start() -> ! {
    let scenario = mailbox().scenario.load(Ordering::Relaxed);
    match run_scenario(scenario) {
        Ok(hash) => {
            mailbox().detail.store(0, Ordering::Relaxed);
            mailbox().hash.store(hash, Ordering::Relaxed);
            mailbox().check.store(0, Ordering::Relaxed);
            mailbox().status.store(STATUS_PASSED, Ordering::Relaxed);
        }
        Err((check, detail)) => {
            mailbox().hash.store(0, Ordering::Relaxed);
            mailbox().detail.store(detail, Ordering::Relaxed);
            mailbox().check.store(check, Ordering::Relaxed);
            mailbox().status.store(STATUS_FAILED, Ordering::Relaxed);
        }
    }
    mailbox().magic.store(MAILBOX_MAGIC, Ordering::Relaxed);

    loop {
        core::hint::spin_loop();
    }
}

#[panic_handler]
fn panic(info: &core::panic::PanicInfo<'_>) -> ! {
    let mut hash = 0x811c_9dc5u32;
    let mut length = 0u32;
    if let Some(message) = info.message().as_str() {
        length = message.len() as u32;
        for byte in message.as_bytes() {
            hash ^= u32::from(*byte);
            hash = hash.wrapping_mul(0x0100_0193);
        }
    }
    let mut line = 0u32;
    let mut column = 0u32;
    let mut file_hash = 0u32;
    if let Some(location) = info.location() {
        line = location.line();
        column = location.column();
        for byte in location.file().as_bytes() {
            file_hash ^= u32::from(*byte);
            file_hash = file_hash.wrapping_mul(0x0100_0193);
        }
    }
    mailbox().detail.store(hash, Ordering::Relaxed);
    mailbox().debug0.store(length, Ordering::Relaxed);
    mailbox().debug1.store(line, Ordering::Relaxed);
    mailbox().debug2.store(file_hash, Ordering::Relaxed);
    mailbox().debug3.store(column, Ordering::Relaxed);
    mailbox().check.store(0xFFFF_FFFF, Ordering::Relaxed);
    mailbox().status.store(STATUS_PANIC, Ordering::Relaxed);
    mailbox().magic.store(MAILBOX_MAGIC, Ordering::Relaxed);
    loop {
        core::hint::spin_loop();
    }
}

/// Run one scenario. `Err((check_id, detail))` is reported through the mailbox.
fn run_scenario(scenario: u32) -> Result<u32, (u32, u32)> {
    match scenario {
        SCENARIO_ALLOC => scenario_alloc(),
        SCENARIO_READ_UIMLK => scenario_read_uimlk_via_app(),
        SCENARIO_CONFIRM_SCREEN => scenario_confirm_screen(),
        SCENARIO_NO_DEVICE => scenario_no_device(),
        other => Err((0xE000_0000 | other, other)),
    }
}

/// Scenario 0: allocator + `Vec` sanity check (ensures the mock firmware can use
/// the same alloc-based protocol core as the desktop).
fn scenario_alloc() -> Result<u32, (u32, u32)> {
    let mut data: Vec<u8> = Vec::with_capacity(16 * 1024);
    for i in 0..16 * 1024u32 {
        data.push((i % 251) as u8);
    }
    if data.len() != 16 * 1024 {
        return Err((1, data.len() as u32));
    }
    let mut state = 0x811c_9dc5u32;
    for byte in &data {
        state ^= u32::from(*byte);
        state = state.wrapping_mul(0x0100_0193);
    }
    Ok(state)
}

/// Scenario 1: full firmware stack on the emulated RP2354.
///
/// Drives the UI (encoder -> Read UIM lock) into the protocol layer, which runs
/// a complete `readuimlk` session against a scripted phone (base handshake,
/// UIMLK switch, Type2Auth 0x52/0x53 with the known test vector, 0x54 state
/// frame, 0x56 exit). The rendered OLED page is then checked cell by cell.
fn scenario_read_uimlk_via_app() -> Result<u32, (u32, u32)> {
    let transport = read_uimlk_transport();

    let mut input = MockInput::new();
    input.push(InputEvent::EncoderCw); // Status -> Read UIM lock
    input.push(InputEvent::EncoderPress); // submit

    let mut app: App<MockDisplay, MockInput, MockClock, MockTransport> = App::new(
        MockDisplay::new(),
        input,
        MockClock::new(),
        AppConfig {
            vid: 0x0482,
            type2: false,
        },
    );
    app.attach(
        transport,
        DeviceInfo {
            vid: 0x0482,
            sn: Some("SKYKA077394".to_string()),
        },
    );

    app.tick();

    let display = app.display();
    if !display.line(0).trim_start().starts_with("readuimlk") {
        return Err((10, fnv1a(display.line(0).as_bytes())));
    }
    if !display.line(1).contains("12345678") {
        return Err((11, fnv1a(display.line(1).as_bytes())));
    }
    if !display.line(2).contains("ctrl 0") {
        return Err((12, fnv1a(display.line(2).as_bytes())));
    }
    let screen_hash = fnv1a(display.screen().as_bytes());

    // The scripted phone must have seen exactly the expected command sequence.
    let transport = app.link_mut().ok_or((13, 0))?;
    let writes = transport.writes.len() as u32;
    let remaining = transport.remaining_steps() as u32;
    let violations = transport.violations.len() as u32;
    if remaining != 0 {
        return Err((14, (remaining << 16) | writes));
    }
    if violations != 0 {
        let first_write = transport.violation_writes.first().copied().unwrap_or(0) as u32;
        mailbox().debug0.store(first_write, Ordering::Relaxed);
        mailbox().debug1.store(writes, Ordering::Relaxed);
        return Err((15, (violations << 16) | writes));
    }

    Ok(screen_hash)
}

/// Scenario 2: destructive operation needs the long-press confirm page.
fn scenario_confirm_screen() -> Result<u32, (u32, u32)> {
    let mut input = MockInput::new();
    for _ in 0..3 {
        input.push(InputEvent::EncoderCw); // Status -> Read -> Write -> Clear UIM lock
    }
    input.push(InputEvent::EncoderPress); // destructive -> confirm page

    let mut app: App<MockDisplay, MockInput, MockClock, MockTransport> = App::new(
        MockDisplay::new(),
        input,
        MockClock::new(),
        AppConfig {
            vid: 0x0482,
            type2: false,
        },
    );
    app.attach(
        MockTransport::new(),
        DeviceInfo {
            vid: 0x0482,
            sn: None,
        },
    );
    app.tick();

    let display = app.display();
    if !display.line(0).contains("CONFIRM") {
        return Err((20, fnv1a(display.line(0).as_bytes())));
    }
    if !display.line(3).contains("NOT UNDOABLE") {
        return Err((21, fnv1a(display.line(3).as_bytes())));
    }
    let screen_hash = fnv1a(display.screen().as_bytes());

    // No protocol frame may be sent from the confirm page.
    if let Some(transport) = app.link_mut() {
        if !transport.writes.is_empty() {
            return Err((22, transport.writes.len() as u32));
        }
    }

    Ok(screen_hash)
}

/// Scenario 3: submitting without a phone shows the NO DEVICE page.
fn scenario_no_device() -> Result<u32, (u32, u32)> {
    let mut input = MockInput::new();
    input.push(InputEvent::EncoderPress); // Status is non-destructive -> submit

    let mut app: App<MockDisplay, MockInput, MockClock, MockTransport> = App::new(
        MockDisplay::new(),
        input,
        MockClock::new(),
        AppConfig {
            vid: 0x0482,
            type2: false,
        },
    );
    app.tick();

    let display = app.display();
    if !display.line(0).contains("NO DEVICE") {
        return Err((30, fnv1a(display.line(0).as_bytes())));
    }
    Ok(fnv1a(display.screen().as_bytes()))
}

/// Scripted phone for a complete `readuimlk` session (no hardware USB).
///
/// The Type2Auth challenge is the desktop test vector
/// (`01 23 45 67 89 AB CD EF`), so the expected `0x53` packet is known:
/// `53050602070601030d0b0c000d0b070f01`.
fn read_uimlk_transport() -> MockTransport {
    let challenge: [u8; 8] = [0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];

    let mut challenge_frame = [0u8; 17];
    challenge_frame[0] = 0x52;
    let encoded = encode_nibbles(&challenge);
    challenge_frame[1..].copy_from_slice(&encoded);

    let (material, _sn) = match parse_sn_to_type2auth("SKYKA077394") {
        Ok(parsed) => parsed,
        Err(_) => (Vec::new(), alloc::string::String::new()),
    };
    let auth_frame = match compute_type2auth_request("uimlk", &challenge, &material) {
        Ok(frame) => frame,
        Err(_) => Vec::new(),
    };

    // 0x74 frame: control 0, lock value 0x12345678 (nibbles 01..08).
    let state_frame = [0x74u8, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08];

    MockTransport::new()
        // enter_base: 0xD8 pre-exit (vid != 0x0FCE), then 0x1C 0x05 handshake
        .on_write(&[0xD8], &[])
        .on_write(&[0x1C, 0x05], &[0x1C, 0x05])
        // switch to UIMLK and authenticate (0x52 challenge -> 0x53 proof)
        .on_write(&[0xE7], &[0xE7])
        .on_write(&[0x52], &challenge_frame)
        .on_write(&auth_frame, &[0x53, 0x01])
        // read state (0x54 -> 0x74 frame) and exit (0x56)
        .on_write(&[0x54], &state_frame)
        .on_write(&[0x56], &[0x56])
}

/// FNV-1a: tiny hash so the host can compare rendered screens without trusting
/// the firmware's textual checks alone.
fn fnv1a(bytes: &[u8]) -> u32 {
    let mut state = 0x811c_9dc5u32;
    for byte in bytes {
        state ^= u32::from(*byte);
        state = state.wrapping_mul(0x0100_0193);
    }
    state
}
