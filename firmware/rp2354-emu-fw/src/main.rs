#![no_main]

//! RP2350-emu test firmware.
//!
//! This binary is the `rp2350-emu` half of the firmware mock tests required by
//! the session rules (docs/plan/13 §1.6): the real firmware logic
//! (`auroku-firmware` + `auroku-core`) is compiled as an RP2350 flash image,
//! booted by the **real Raspberry Pi RP2350 bootrom** (vendored under `rom/`)
//! in the emulator, with a scripted phone transport instead of hardware USB.
//!
//! Flash layout (see `link.x`):
//! - `0x1000_0000`: vector table (initial SP, reset handler, fault handlers);
//! - `0x1000_0040`: 20-byte picobin IMAGE_DEF block (ARM, Secure, RP2350);
//! - `0x1000_0060`: reset handler (`_start`) and firmware code.
//!
//! Host protocol: `firmware/emu-tests` loads the bootrom + flash image, runs
//! cycles and polls the SRAM mailbox at `0x2007_0000`:
//!
//! | word | field     | meaning                                            |
//! |------|-----------|----------------------------------------------------|
//! | 0    | scenario  | written by the host before boot                    |
//! | 1    | status    | 0 = running, 1 = passed, 2 = failed, 3 = panic      |
//! | 2    | check     | failing check id (0 on success)                     |
//! | 3    | detail    | extra diagnostic / panic message hash               |
//! | 4    | hash      | FNV-1a hash of the rendered OLED screen             |
//! | 5    | magic     | `0x4155_5242` ("AURB") written last, marks valid    |
//! | 6    | debug0    | first mock violation hash / panic message length    |
//! | 7    | debug1    | write count / panic line                            |
//!
//! On failure the host harness prints the check id; `rp2350-emu-tui` can then be
//! pointed at the same bootrom/flash pair to inspect registers and memory.

